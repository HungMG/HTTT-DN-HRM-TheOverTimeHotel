const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const code = fs.readFileSync("src/OvertimeHotel.HRM.WebAdmin/wwwroot/js/account-request-popup.js", "utf8");
const listeners = {};
const employee = { value: "7", selectedOptions: [{ value: "7", text: "Nguyen An · an@example.invalid" }], addEventListener() {} };
const match = { value: "10", dataset: { employeeId: "7", roleId: "1", roleName: "Employee", roleDisplay: "Nhan vien" } };
const other = { value: "20", dataset: { employeeId: "8" } };
const contract = { options: [{ value: "" }, match, other], value: "", disabled: true, selectedIndex: 0, addEventListener() {}, get selectedOptions() { return this.options.filter(x => x.value === this.value); } };
const role = { value: "" }, username = { value: "" }, submit = { disabled: true };
const form = { action: "/YeuCauTaiKhoan/Create?popup=true", addEventListener(name, cb) { listeners[name] = cb; } };
const nodes = { "#popupEmployeeId": employee, "#popupRoleId": role, "[data-contract-select]": contract, "[data-username-input]": username, "#popupBtnSubmit": submit, "[data-create-request-form]": form };
const container = { querySelector: key => nodes[key] || null };
let sent, success, error;
const window = {};
vm.runInNewContext(code, { window, console, Error, FormData: class { constructor(form) { this.form = form; } }, fetch: async (url, options) => { sent = { url, options }; return { ok: true, headers: { get: () => "application/json" }, json: async () => ({ success: true, message: "Sent" }) }; } });
window.initAccountRequestPopup(container, message => { success = message; }, message => { error = message; });
assert.equal(contract.value, "10");
assert.equal(other.disabled, true);
assert.equal(role.value, "1");
assert.equal(username.value, "n.an");
assert.equal(submit.disabled, false);
(async () => {
  let prevented = false;
  await listeners.submit({ preventDefault() { prevented = true; } });
  assert.equal(prevented, true);
  assert.equal(sent.url, form.action);
  assert.equal(sent.options.method, "POST");
  assert.equal(success, "Sent");
  assert.equal(error, undefined);
  console.log("PASS preselected employee, contract filtering and request submission");
  form.dataset = { employeeOnly: "true" };
  const restriction = { hidden: true };
  nodes["[data-role-restriction]"] = restriction;
  match.dataset.roleName = "Manager";
  match.dataset.roleId = "2";
  window.initAccountRequestPopup(container, () => {}, () => {});
  assert.equal(restriction.hidden, false, "Show why the requested role cannot be issued");
  assert.equal(submit.disabled, true, "Prevent submitting a role unavailable to HR/Admin");
  form.dataset.employeeOnly = "false";
  window.initAccountRequestPopup(container, () => {}, () => {});
  assert.equal(restriction.hidden, true, "IT should not see the HR/Admin restriction");
  assert.equal(submit.disabled, false, "IT can submit the manager role");
  console.log("PASS restricted roles show an explanation and cannot be submitted");
  const filterEvents = {};
  const employeeOptions = [{ value: "" }, { value: "7" }, { value: "8" }];
  const roleFilter = { value: "Manager", addEventListener(name, cb) { filterEvents[name] = cb; } };
  nodes["[data-role-filter]"] = roleFilter;
  nodes["#popup-employee-role-data"] = { textContent: JSON.stringify({ 7: { RoleName: "Employee" }, 8: { RoleName: "Manager" } }) };
  employee.options = employeeOptions;
  employee.value = "7";
  window.initAccountRequestPopup(container, () => {}, () => {});
  assert.equal(employeeOptions[1].hidden, true, "Employee must be hidden when filtering managers");
  assert.equal(employeeOptions[2].hidden, false, "Manager must remain available");
  assert.equal(employee.value, "", "Clear a selection that no longer matches");
  roleFilter.value = "";
  filterEvents.change();
  assert.equal(employeeOptions[1].hidden, false, "All roles must be visible when filter is cleared");
  const empty = { hidden: true };
  nodes["[data-role-filter-empty]"] = empty;
  roleFilter.value = "IT";
  window.initAccountRequestPopup(container, () => {}, () => {});
  assert.equal(empty.hidden, false, "Explain when no employee matches the selected role");
  console.log("PASS role filter and selection reset");
})().catch(error => { console.error(error); process.exitCode = 1; });
