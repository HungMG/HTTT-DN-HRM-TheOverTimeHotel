-- A real write conflict serializes all seat mutations, including REPEATABLE READ.
-- ponytail: one hotel-wide row; partition by organization if multi-hotel scale is added.
CREATE TABLE public.salary_write_guard (
    singleton boolean PRIMARY KEY CHECK (singleton), revision bigint NOT NULL
);
INSERT INTO public.salary_write_guard VALUES (true, 0);

-- Observed migration-time projection, deliberately not a claim about hire-time role.
-- This immutable baseline avoids changing inferred past whenever the worker syncs profiles.
CREATE TABLE public.salary_position_baseline (
    ma_nhan_vien integer PRIMARY KEY REFERENCES public.nhan_vien(ma_nhan_vien) ON DELETE CASCADE,
    observed_date date NOT NULL,
    ma_chuc_vu integer REFERENCES public.chuc_vu(ma_chuc_vu) ON DELETE RESTRICT
);
INSERT INTO public.salary_position_baseline
    SELECT ma_nhan_vien,CURRENT_DATE,ma_chuc_vu FROM public.nhan_vien;

CREATE FUNCTION public.salary_serialize_write() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    UPDATE public.salary_write_guard SET revision=revision+1 WHERE singleton;
    IF NOT FOUND THEN RAISE EXCEPTION 'Salary serialization row is missing'; END IF;
    RETURN NULL;
END $$;

CREATE FUNCTION public.salary_check_gm_timeline() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    -- Old rows have no historical snapshot. Treat the known current GM conservatively;
    -- never infer a past promotion date or silently rewrite business history.
    IF EXISTS (
        WITH events AS (
            -- A signed role history supersedes the observed projection. Retain the
            -- projection when the first signed event is still in the future.
            SELECT b.ma_nhan_vien,greatest(b.observed_date,n.ngay_vao_lam) AS effective,b.ma_chuc_vu AS position,
                   0 AS priority,0::bigint AS source_id
            FROM public.salary_position_baseline b JOIN public.nhan_vien n USING (ma_nhan_vien)
            WHERE NOT EXISTS (SELECT FROM public.hop_dong h WHERE h.ma_nhan_vien=b.ma_nhan_vien
                AND h.ma_chuc_vu_ky_ket IS NOT NULL AND h.ngay_bat_dau<=b.observed_date)
              AND NOT EXISTS (SELECT FROM public.hop_dong h JOIN public.phu_luc_luong p USING (ma_hop_dong)
                WHERE h.ma_nhan_vien=b.ma_nhan_vien AND p.ma_chuc_vu_moi IS NOT NULL AND p.ngay_hieu_luc<=b.observed_date)
            UNION ALL
            -- New employees created after migration normally sign a snapshot at hire.
            SELECT n.ma_nhan_vien,n.ngay_vao_lam,n.ma_chuc_vu,0,0::bigint
            FROM public.nhan_vien n WHERE NOT EXISTS (
                SELECT FROM public.salary_position_baseline b WHERE b.ma_nhan_vien=n.ma_nhan_vien)
              AND (n.trang_thai IN ('DANG_LAM','TAM_NGHI') OR n.ngay_thoi_viec IS NOT NULL)
            UNION ALL
            SELECT h.ma_nhan_vien,h.ngay_bat_dau,h.ma_chuc_vu_ky_ket,1,h.ma_hop_dong::bigint
            FROM public.hop_dong h WHERE h.ma_chuc_vu_ky_ket IS NOT NULL
            UNION ALL
            SELECT h.ma_nhan_vien,p.ngay_hieu_luc,p.ma_chuc_vu_moi,2,p.ma_phu_luc
            FROM public.hop_dong h JOIN public.phu_luc_luong p USING (ma_hop_dong)
            WHERE p.ma_chuc_vu_moi IS NOT NULL
        ), effective_events AS (
            SELECT DISTINCT ON (ma_nhan_vien,effective) * FROM events
            ORDER BY ma_nhan_vien,effective,priority DESC,source_id DESC
        ), ordered AS (
            SELECT *,lead(effective) OVER (PARTITION BY ma_nhan_vien ORDER BY effective) AS next_date
            FROM effective_events
        ), seats AS (
            SELECT o.ma_nhan_vien, daterange(o.effective,
                least(coalesce(o.next_date,'infinity'::date),
                      CASE WHEN n.ngay_thoi_viec IS NULL THEN 'infinity'::date ELSE n.ngay_thoi_viec+1 END),'[)') AS during
            FROM ordered o JOIN public.chuc_vu c ON c.ma_chuc_vu=o.position
            JOIN public.nhan_vien n ON n.ma_nhan_vien=o.ma_nhan_vien
            WHERE c.nhom_luong='TONG_GIAM_DOC'
              AND (n.ngay_thoi_viec IS NULL OR o.effective<=n.ngay_thoi_viec)
        )
        SELECT FROM seats a JOIN seats b ON a.ma_nhan_vien<b.ma_nhan_vien AND a.during && b.during
    ) THEN RAISE EXCEPTION 'General director appointments overlap; verify dated history'; END IF;
    RETURN NULL;
END $$;

CREATE FUNCTION public.salary_guard_appendix() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
DECLARE h public.hop_dong; affected record;
BEGIN
    -- Same lock as payroll calculation/approval in the application.
    PERFORM pg_advisory_xact_lock(2026101509);
    FOR affected IN
        SELECT OLD.ma_hop_dong AS contract_id, OLD.ngay_hieu_luc AS effective WHERE TG_OP IN ('UPDATE','DELETE')
        UNION ALL
        SELECT NEW.ma_hop_dong,NEW.ngay_hieu_luc WHERE TG_OP IN ('INSERT','UPDATE')
    LOOP
        SELECT * INTO STRICT h FROM public.hop_dong WHERE ma_hop_dong=affected.contract_id FOR UPDATE;
        -- Conservative guard extends until contract end, including later locked periods.
        PERFORM 1 FROM public.ky_luong WHERE den_ngay>=affected.effective
            AND tu_ngay<=coalesce(h.ngay_ket_thuc,'infinity'::date) FOR UPDATE;
        IF EXISTS (SELECT FROM public.ky_luong WHERE (trang_thai IN ('CHO_DUYET','DA_DUYET','KHOA_SO','DA_THANH_TOAN')
                OR ngay_duyet IS NOT NULL
                OR (ngay_gui_duyet IS NOT NULL AND ngay_duyet IS NULL AND (ly_do_tu_choi IS NULL OR ly_do_tu_choi='')))
            AND den_ngay>=affected.effective AND tu_ngay<=coalesce(h.ngay_ket_thuc,'infinity'::date)) THEN
            RAISE EXCEPTION 'Salary amendment affects an approved or locked payroll period';
        END IF;
    END LOOP;
    IF TG_OP <> 'DELETE' THEN
        SELECT * INTO STRICT h FROM public.hop_dong WHERE ma_hop_dong=NEW.ma_hop_dong;
        IF NEW.ngay_hieu_luc<h.ngay_bat_dau OR NEW.ngay_hieu_luc>coalesce(h.ngay_ket_thuc,'infinity'::date)
           OR h.trang_thai='DA_CHAM_DUT' THEN RAISE EXCEPTION 'Amendment is outside the active contract'; END IF;
        IF NEW.ma_chuc_vu_moi IS NOT NULL AND (h.ma_chuc_vu_ky_ket IS NULL OR h.ma_phong_ban_ky_ket IS NULL) THEN
            RAISE EXCEPTION 'Position history requires verified contract snapshots';
        END IF;
        IF NEW.ma_chuc_vu_moi IS NOT NULL AND NOT EXISTS (
            SELECT FROM public.chuc_vu c WHERE c.ma_chuc_vu=NEW.ma_chuc_vu_moi AND c.nhom_luong IS NOT NULL
              AND (c.ma_phong_ban IS NULL OR c.ma_phong_ban=NEW.ma_phong_ban_moi)
        ) THEN RAISE EXCEPTION 'Unclassified or department-incompatible position'; END IF;
        RETURN NEW;
    END IF;
    RETURN OLD;
END $$;

