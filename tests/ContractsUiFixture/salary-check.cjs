const assert = require('node:assert/strict');
const { chromium } = require('/home/bryan/.agents/skills/playwright-skill/node_modules/playwright');
const base = process.env.CONTRACT_FIXTURE_URL || 'http://127.0.0.1:18767';
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: '/home/bryan/.cache/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-linux64/chrome-headless-shell', args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1366, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/HopDong/SalaryQuote?*', async route => {
    const education = new URL(route.request().url()).searchParams.get('education');
    if (education === 'Trung cấp') await new Promise(resolve => setTimeout(resolve, 200));
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ minimum: education === 'Cao đẳng' ? 7000000 : 6000000, maximum: 9000000, probationSalary: education === 'Cao đẳng' ? 5950000 : 5100000, tenureMonths: 0 }) }).catch(() => {});
  });
  await page.goto(base + '/HopDong/SalaryReviews');
  assert(await page.getByRole('heading', { name: 'Xem xét lương', exact: true }).first().isVisible());
  const missingSalary = page.locator('.salary-review-row').filter({ hasText: 'Hợp đồng #2333' });
  assert(await missingSalary.isVisible());
  assert.match(await missingSalary.innerText(), /Cần xác minh/);
  assert.match(await missingSalary.innerText(), /Chưa có mức lương hợp lệ/);
  assert(await page.locator('.salary-review-row').filter({ hasText: 'Trần Minh Anh' }).isVisible());
  await page.goto(base + '/HopDong?occupiedGm=true');
  assert(await page.locator('[data-contract-create-error]').isVisible());
  assert.match(await page.locator('[data-contract-create-error]').innerText(), /đã có Tổng Giám Đốc/);
  assert.equal(await page.locator('.modal-backdrop').count(), 0);
  await page.goto(base + '/HopDong');
  await page.locator('[data-bs-target="#createContractModal"]').first().click();
  const form = page.locator('#createContractModal form');
  await form.locator('[name="TrinhDo"]').selectOption('Trung cấp');
  await form.locator('[name="Contract.HinhThucHopDong"]').selectOption('THU_VIEC');
  await form.locator('[name="TrinhDo"]').selectOption('Cao đẳng');
  await page.waitForFunction(() => document.querySelector('[name="Contract.LuongCoBan"]').value.replace(/,/g, '') === '5950000');
  assert.equal(await form.locator('[name="Contract.LuongCoBan"]').inputValue(), '5,950,000');
  assert(await form.locator('[name="Contract.LuongCoBan"]').evaluate(el => el.readOnly));
  assert(await form.locator('[name="Contract.NgayKetThuc"]').evaluate(el => el.readOnly));
  assert.match(await form.locator('[data-salary-band]').innerText(), /7.000.000/);
  await form.locator('[name="Contract.NgayBatDau"]').evaluate(el => { el.value = '2026-12-31'; el.dispatchEvent(new Event('change', { bubbles: true })); });
  assert.equal(await form.locator('[name="Contract.NgayKetThuc"]').inputValue(), '2027-02-27');
  await form.locator('[name="Contract.HinhThucHopDong"]').selectOption('CHINH_THUC');
  assert(!await form.locator('[name="Contract.LuongCoBan"]').evaluate(el => el.readOnly));
  await form.locator('[name="Contract.LuongCoBan"]').fill('6999999');
  await page.waitForFunction(() => document.querySelector('[name="Contract.LuongCoBan"]').min === '7000000');
  assert(!await form.locator('[name="Contract.LuongCoBan"]').evaluate(el => el.validity.valid));
  for (const [name, viewport] of [['desktop', {width:1366,height:1000}], ['mobile', {width:390,height:844}]]) {
    await page.setViewportSize(viewport);
    await page.screenshot({path: '/tmp/hrm-salary-form-' + name + '.png'});
    assert(await page.locator('#createContractModal .modal-content').evaluate(el => el.getBoundingClientRect().right <= innerWidth));
  }
  await page.locator('#createContractModal [data-bs-dismiss="modal"]').first().click();
  await page.locator('#createContractModal').waitFor({state:'hidden'});
  await page.evaluate(() => {
    const region = document.createElement('section'); region.dataset.salaryAmendmentsUrl = '/HopDong/SalaryAmendments?id=7'; document.body.append(region); window.SalaryContract.init(document);
  });
  const amendment = page.locator('[data-salary-amendment-form]');
  await amendment.waitFor({ state: 'attached' });
  await page.locator('summary').click();
  await amendment.locator('[data-salary-band]').getByText('Mức lương hiện tại:', { exact: false }).waitFor();
  assert.match(await amendment.locator('[data-salary-band]').innerText(), /Mức lương hiện tại:\s*Chưa xác định/);
  await amendment.locator('[name="effectiveDate"]').fill('2027-02-01');
  await amendment.locator('[name="salary"]').fill('8000000');
  await amendment.locator('[name="reason"]').fill('Xét thâm niên');
  assert(await amendment.locator('[name="positionId"]').isDisabled());
  assert(await amendment.locator('[name="departmentId"]').isDisabled());
  let salaryOnlyChecked = false;
  await page.route('**/HopDong/AddSalaryAmendment', route => {
    const body = route.request().postData() || '';
    assert(!body.includes('name="positionId"') && !body.includes('name="departmentId"'), 'Salary-only amendment must inherit effective position on server');
    salaryOnlyChecked = true;
    return route.fulfill({ status:400, contentType:'text/plain', body:'Kỳ lương đã khóa.' });
  });
  await amendment.locator('[type="submit"]').click();
  await amendment.locator('[data-amendment-error]').filter({ hasText: 'Kỳ lương đã khóa.' }).waitFor();
  assert.equal(await amendment.locator('[name="salary"]').inputValue(), '8,000,000');
  assert(salaryOnlyChecked);
  await page.unroute('**/HopDong/AddSalaryAmendment');
  await page.route('**/HopDong/AddSalaryAmendment', route => route.fulfill({contentType:'application/json',body:JSON.stringify({success:true,message:'Đã lưu phụ lục thử nghiệm.'})}));
  await amendment.locator('[type="submit"]').click();
  await page.getByText('Đã lưu phụ lục thử nghiệm.').waitFor();
  const duplicates = await page.evaluate(() => { const ids = [...document.querySelectorAll('[id]')].map(el => el.id); return ids.filter((id, i) => ids.indexOf(id) !== i); });
  assert.deepEqual(duplicates, []);
  assert.deepEqual(errors, []);
  const expired = await page.request.get(base + '/HopDong/SalaryAmendments?id=7&expired=true');
  const expiredHtml = await expired.text();
  assert.match(expiredHtml, /Hợp đồng không có hiệu lực vào ngày/);
  assert(!expiredHtml.includes('data-salary-amendment-form'), 'No misleading amendment form when next month is outside the contract');
  await browser.close();
  console.log('Salary browser checks passed: quote race, probation, month-end dates, official bounds, responsive form, amendment errors/save, duplicate IDs.');
})().catch(error => { console.error(error); process.exit(1); });
